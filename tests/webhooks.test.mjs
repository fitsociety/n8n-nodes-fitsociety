// Model the Public API response cache separately from the callback upsert store.
function cachedRegistration(overrides = {}) {
	const h = context([], overrides);
	const request = h.ctx.helpers.httpRequestWithAuthentication;
	const cache = new Map();
	let loseResponse = false;
	h.ctx.helpers.httpRequestWithAuthentication = async (credential, options) => {
		if (options.method !== 'POST') return request(credential, options);
		const requestKey = options.headers['Idempotency-Key'];
		if (cache.has(requestKey)) return structuredClone(cache.get(requestKey));
		const response = await request(credential, options);
		cache.set(requestKey, structuredClone(response));
		if (loseResponse) {
			loseResponse = false;
			throw new Error('Response lost after server commit');
		}
		return response;
	};
	return {
		...h,
		loseNextResponse: () => {
			loseResponse = true;
		},
	};
}

test('reactivating after deletion creates a real active subscription despite cached POST responses', async () => {
	const h = cachedRegistration();
	const node = new FitsocietyTrigger();
	await node.webhookMethods.default.create.call(h.ctx);
	await node.webhookMethods.default.delete.call(h.ctx);
	assert.deepEqual(h.records(), []);
	await node.webhookMethods.default.create.call(h.ctx);
	assert.equal(h.records().length, 1);
	assert.equal(h.records()[0].status, 'active');
	assert.equal(h.records()[0].id, h.state.subscriptionId);
	assert.equal(await node.webhookMethods.default.checkExists.call(h.ctx), true);
	assert.deepEqual(Object.keys(h.state), ['subscriptionId']);
});

test('changing events A to B to A reconciles the active subscription instead of replaying old success', async () => {
	let events = ['client.created'];
	const h = cachedRegistration({ getNodeParameter: () => events });
	const node = new FitsocietyTrigger();
	for (const selection of [['client.created'], ['booking.created'], ['client.created']]) {
		events = selection;
		await node.webhookMethods.default.create.call(h.ctx);
		assert.equal(h.records().length, 1);
		assert.deepEqual(h.records()[0].events, selection);
		assert.equal(await node.webhookMethods.default.checkExists.call(h.ctx), true);
	}
});

test('a new create invocation after an uncertain response relies on atomic callback upsert without duplicates', async () => {
	const h = cachedRegistration();
	const node = new FitsocietyTrigger();
	h.loseNextResponse();
	await assert.rejects(node.webhookMethods.default.create.call(h.ctx));
	assert.equal(h.records().length, 1);
	assert.deepEqual(h.state, {});
	await node.webhookMethods.default.create.call(h.ctx);
	assert.equal(h.records().length, 1);
	assert.equal(h.records()[0].id, h.state.subscriptionId);
	const writes = h.calls.filter((call) => call.method === 'POST');
	assert.equal(writes.length, 2);
	assert.notEqual(writes[0].headers['Idempotency-Key'], writes[1].headers['Idempotency-Key']);
	assert.deepEqual(Object.keys(h.state), ['subscriptionId']);
});


test('invalid webhook deliveries return a constant 401 without workflow data or state changes', async () => {
 const wrongCompany = { ...payload, companyId: 'another-company' };
 const badEvent = { ...payload, type: 'booking.created' };
 for (const [rawBody, headers] of [
  [Buffer.from(JSON.stringify(payload)), { ...signed(), 'x-fitsociety-webhook-signature': 'v1=' + '0'.repeat(64) }],
  [Buffer.from('{'), signed()],
  [Buffer.from(JSON.stringify(payload)), signed(payload, String(Math.floor(Date.now() / 1000) - 301))],
  [Buffer.from(JSON.stringify(wrongCompany)), signed(wrongCompany)],
  [Buffer.from(JSON.stringify(badEvent)), signed(badEvent)],
 ]) {
  const sent = [];
  const response = { status(code) { sent.push({ code }); return this; }, json(body) { sent[sent.length - 1].body = body; return this; } };
  const h = context([], { getRequestObject: () => ({ rawBody }), getHeaderData: () => headers, getResponseObject: () => response });
  const result = await new FitsocietyTrigger().webhook.call(h.ctx);
  assert.deepEqual(sent, [{ code: 401, body: { error: 'Invalid FITsociety webhook' } }]);
  assert.deepEqual(result, { noWebhookResponse: true });
  assert.equal(result.workflowData, undefined);
  assert.deepEqual(h.state, {});
  assert.deepEqual(h.calls, []);
 }
});

