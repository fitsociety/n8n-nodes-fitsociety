function context(records = [], overrides = {}) {
	const state = {};
	const calls = [];
	let current = records.map((r) => ({ ...r }));
	const ctx = {
		getNode: () => ({
			id: 'node',
			name: 'FITsociety',
			type: 'fitsocietyTrigger',
			typeVersion: 1,
			webhookId,
		}),
		getCredentials: async () => ({
			apiBaseUrl: 'https://api.example.com/public/v1',
			companyId: 'company-test',
			clientId: 'test-client',
			clientSecret: secret,
			oauthTokenData: {
				integration_key: 'n8n',
				client_id: 'test-client',
				company_id: 'company-test',
			},
		}),
		getNodeParameter: (name) => (name === 'events' ? ['client.created'] : undefined),
		getNodeWebhookUrl: () => 'https://n8n.example.com/webhook/new',
		getWorkflowStaticData: () => state,
		helpers: {
			httpRequestWithAuthentication: async (_credential, options) => {
				calls.push(options);
				const path = new URL(options.url).pathname.replace('/public/v1', '');
				if (options.method === 'GET' && path === '/n8n/webhooks')
					return { statusCode: 200, body: { data: current } };
				if (options.method === 'GET') {
					const found = current.find((r) => path.endsWith('/' + r.id));
					if (!found) return { statusCode: 404, body: { error: { message: 'Not found' } } };
					return { statusCode: 200, body: { data: found } };
				}
				if (options.method === 'POST') {
					const existing = current.find((r) => r.url === options.body.url);
					const record = {
						id: existing?.id || 'subscription-new',
						url: options.body.url,
						events: options.body.events,
						status: 'active',
						signingKeyHash: createHash('sha256').update(options.body.signingSecret).digest('hex'),
					};
					current = current.filter((r) => r.id !== record.id).concat(record);
					return { statusCode: 200, body: { data: record } };
				}
				if (options.method === 'DELETE') {
					current = current.filter((r) => !path.endsWith('/' + r.id));
					return { statusCode: 200, body: { data: { deleted: true } } };
				}
				throw new Error('Unexpected request');
			},
		},
		...overrides,
	};
	return { ctx, state, calls, records: () => current };
}
