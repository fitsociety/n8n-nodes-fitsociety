// Independent test sender; the frozen signature below was generated by the backend signer.
function canonical(value) {
	if (value === null || typeof value !== 'object') return JSON.stringify(value);
	if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
	return (
		'{' +
		Object.keys(value)
			.sort()
			.map((k) => JSON.stringify(k) + ':' + canonical(value[k]))
			.join(',') +
		'}'
	);
}
function signed(body = payload, timestamp = String(Math.floor(Date.now() / 1000))) {
	return {
		'x-fitsociety-webhook-event': body.type,
		'x-fitsociety-webhook-delivery': 'delivery-test',
		'x-fitsociety-webhook-timestamp': timestamp,
		'x-fitsociety-webhook-signature':
			'v1=' +
			createHmac('sha256', key)
				.update([timestamp, 'delivery-test', body.id, canonical(body)].join('.'))
				.digest('hex'),
	};
}
